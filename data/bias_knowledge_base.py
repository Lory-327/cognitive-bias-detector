# 确保对称性: 如果 (A,B) 存在, (B,A) 也自动生效
def _ensure_symmetry():
    """确保交叉调整规则的对称性"""
    additions = {}
    for (a, b), v in CROSSOVER_ADJUSTMENT.items():
        if (b, a) not in CROSSOVER_ADJUSTMENT:
            additions[(b, a)] = v
    CROSSOVER_ADJUSTMENT.update(additions)

_ensure_symmetry()


#辅助函数

def get_bias_info(bias_id: str) -> dict:
    """
    根据偏差ID或中文名称获取偏差详细信息。

    Args:
        bias_id: 偏差的英文ID或中文名称

    Returns:
        包含偏差详细信息的字典,未找到返回空字典
    """
    # 先尝试直接匹配中文名称
    if bias_id in BIAS_DATABASE:
        return BIAS_DATABASE[bias_id]

    # 再尝试匹配英文ID
    for name, info in BIAS_DATABASE.items():
        if info.get("id") == bias_id:
            return info

    return {}


def get_crossover_adjustment(bias_a: str, bias_b: str) -> dict:
    """
    获取两个偏差之间的交叉调整规则。

    Args:
        bias_a: 第一个偏差的中文名称
        bias_b: 第二个偏差的中文名称

    Returns:
        包含primary_boost、secondary_decay和distinguish_hint的字典
        未找到返回空字典
    """
    key = (bias_a, bias_b)
    if key in CROSSOVER_ADJUSTMENT:
        return CROSSOVER_ADJUSTMENT[key]
    return {}


def get_biases_by_category(category: str) -> list:
    """
    按类别获取所有偏差。

    Args:
        category: 类别名称,如"投入类"、"信息类"等

    Returns:
        该类别下所有偏差的名称列表
    """
    return [name for name, info in BIAS_DATABASE.items() if info.get("category") == category]


def get_all_bias_names() -> list:
    """获取所有偏差的中文名称列表。"""
    return list(BIAS_DATABASE.keys())


def get_all_bias_ids() -> list:
    """获取所有偏差的英文ID列表。"""
    return [info["id"] for info in BIAS_DATABASE.values()]


def search_biases_by_keyword(keyword: str) -> list:
    """
    根据关键词搜索偏差。

    Args:
        keyword: 搜索关键词

    Returns:
        包含该关键词的偏差名称列表(在名称、描述、触发词中搜索)
    """
    results = []
    keyword_lower = keyword.lower()
    for name, info in BIAS_DATABASE.items():
        # 搜索名称
        if keyword_lower in name.lower():
            results.append(name)
            continue
        # 搜索描述
        if keyword_lower in info.get("description", "").lower():
            results.append(name)
            continue
        # 搜索触发关键词
        triggers = info.get("trigger_keywords", [])
        if any(keyword_lower in t.lower() for t in triggers):
            results.append(name)
            continue
    return list(set(results))


